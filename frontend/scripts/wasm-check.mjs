// Fails when src/wasm was built from a different crates/ tree than the one on disk, or when
// wasm-pack's generated .gitignore is still present. Needs git, not Rust.

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { buildJsonPath, cratesTreeHash, outDir } from "./wasm-build.mjs";

const problems = [];

if (!existsSync(buildJsonPath)) {
  problems.push("src/wasm/BUILD.json is missing; run `npm run wasm:build`.");
} else {
  const build = JSON.parse(readFileSync(buildJsonPath, "utf8"));
  const expected = cratesTreeHash();
  if (build.cratesTreeHash !== expected) {
    problems.push(
      `src/wasm was built from crates tree ${build.cratesTreeHash}, the working tree is ${expected}; run \`npm run wasm:build\` and commit src/wasm/.`,
    );
  }
}

for (const file of ["xiv_craft.js", "xiv_craft.d.ts", "xiv_craft_bg.wasm"]) {
  if (!existsSync(join(outDir, file))) problems.push(`src/wasm/${file} is missing.`);
}
if (existsSync(join(outDir, ".gitignore"))) {
  problems.push("src/wasm/.gitignore (generated by wasm-pack) would un-commit the artifact; delete it.");
}

if (problems.length > 0) {
  for (const p of problems) console.error(`wasm:check: ${p}`);
  process.exit(1);
}
console.log("wasm:check: src/wasm matches the crates tree on disk.");
