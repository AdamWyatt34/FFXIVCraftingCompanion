"use client";

import { useState, useRef, useEffect } from "react";
import { Share2, Link as LinkIcon, FileText } from "lucide-react";
import { useToast } from "@/components/ui/Toast";
import type { GearSetDto } from "@/types/gear";
import { JOB_INFO, type GearJob } from "@/lib/gear-constants";

interface GearShareButtonProps {
  job: string;
  level: number;
  profile: string;
  gearSet: GearSetDto;
}

function formatGearSetText(gearSet: GearSetDto): string {
  const jobInfo = JOB_INFO[gearSet.job as GearJob];
  const jobName = jobInfo?.fullName ?? gearSet.job;
  const isDoH = jobInfo?.category === "DoH";

  const lines: string[] = [
    `=== ${jobName} Gear Set (Lv. ${gearSet.level}, ${gearSet.profile.displayName}) ===`,
  ];

  for (const slot of gearSet.slots) {
    if (slot.recommendation) {
      lines.push(
        `${slot.slotName}: ${slot.recommendation.name} (iLv ${slot.recommendation.itemLevel})`,
      );
    } else {
      lines.push(`${slot.slotName}: (empty)`);
    }
  }

  lines.push("");
  const stats = gearSet.totalStats;
  if (isDoH) {
    lines.push(
      `Total: Craftsmanship ${stats.craftsmanship.toLocaleString()} / Control ${stats.control.toLocaleString()} / CP ${stats.cp.toLocaleString()}`,
    );
  } else {
    lines.push(
      `Total: Gathering ${stats.gathering.toLocaleString()} / Perception ${stats.perception.toLocaleString()} / GP ${stats.gp.toLocaleString()}`,
    );
  }
  lines.push("Generated by FFXIV Crafting Companion");

  return lines.join("\n");
}

export function GearShareButton({
  job,
  level,
  profile,
  gearSet,
}: GearShareButtonProps) {
  const [isOpen, setIsOpen] = useState(false);
  const dropdownRef = useRef<HTMLDivElement>(null);
  const { toast } = useToast();

  // Close dropdown on outside click
  useEffect(() => {
    if (!isOpen) return;
    function handleClick(e: MouseEvent) {
      if (
        dropdownRef.current &&
        !dropdownRef.current.contains(e.target as Node)
      ) {
        setIsOpen(false);
      }
    }
    document.addEventListener("mousedown", handleClick);
    return () => document.removeEventListener("mousedown", handleClick);
  }, [isOpen]);

  // Close on Escape
  useEffect(() => {
    if (!isOpen) return;
    function handleKey(e: KeyboardEvent) {
      if (e.key === "Escape") setIsOpen(false);
    }
    document.addEventListener("keydown", handleKey);
    return () => document.removeEventListener("keydown", handleKey);
  }, [isOpen]);

  const copyLink = async () => {
    const url = `${window.location.origin}/gear?job=${encodeURIComponent(job)}&level=${level}&profile=${encodeURIComponent(profile)}`;
    try {
      await navigator.clipboard.writeText(url);
      toast("Gear set link copied!", "success");
    } catch {
      toast("Failed to copy link", "error");
    }
    setIsOpen(false);
  };

  const copyText = async () => {
    const text = formatGearSetText(gearSet);
    try {
      await navigator.clipboard.writeText(text);
      toast("Gear set copied as text!", "success");
    } catch {
      toast("Failed to copy text", "error");
    }
    setIsOpen(false);
  };

  return (
    <div className="relative" ref={dropdownRef}>
      <button
        onClick={() => setIsOpen(!isOpen)}
        className="flex items-center gap-2 px-3 py-2 rounded-lg bg-bg-elevated border border-border text-text-secondary hover:text-gold hover:border-gold/50 transition-colors text-sm"
        aria-label="Share gear set"
        aria-expanded={isOpen}
      >
        <Share2 size={16} />
        Share
      </button>

      {isOpen && (
        <div className="absolute right-0 top-full mt-1 w-48 rounded-lg bg-bg-elevated border border-border shadow-lg z-20 overflow-hidden animate-fade-in">
          <button
            onClick={copyLink}
            className="flex items-center gap-2 w-full px-3 py-2.5 text-sm text-text-primary hover:bg-bg-surface transition-colors"
          >
            <LinkIcon size={14} className="text-text-muted" />
            Copy link
          </button>
          <button
            onClick={copyText}
            className="flex items-center gap-2 w-full px-3 py-2.5 text-sm text-text-primary hover:bg-bg-surface transition-colors border-t border-border"
          >
            <FileText size={14} className="text-text-muted" />
            Copy as text
          </button>
        </div>
      )}
    </div>
  );
}
